"""Plot the quickstart run: series, planted anomalies, and both detectors.

Same seeds and settings as examples/quickstart.py. Needs matplotlib
(optional, only for this script): pip install matplotlib

    python examples/plot_results.py        # writes docs/detection.png

All data is synthetic, generated by ts_anomaly.TimeSeriesGenerator.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from ts_anomaly import (
    AnomalyDetector,
    TimeSeriesGenerator,
    TransformerAutoencoder,
    moving_zscore,
    point_adjusted_f1,
    roc_auc,
    scores_to_labels,
)
from ts_anomaly.train import train_autoencoder

BLUE, RED, GREEN, GREY = "#2e86ab", "#e4572e", "#59a14f", "#555555"


def episodes(labels):
    out, start = [], None
    for i, v in enumerate(labels):
        if v and start is None:
            start = i
        if not v and start is not None:
            out.append((start, i))
            start = None
    if start is not None:
        out.append((start, len(labels)))
    return out


def main():
    series, labels = TimeSeriesGenerator(seed=7, trend_slope=0.0).generate(
        n=1500, n_episodes=10, anomaly_start=0.6
    )
    train = series[:720]
    ae = TransformerAutoencoder(window=24, d_model=12, d_ff=24, seed=42)
    train_autoencoder(ae, train, epochs=20, batch_size=64, lr=0.1,
                      patience=5, stride=4, seed=0)
    det = AnomalyDetector(ae)
    thr = det.fit_threshold(train, quantile=0.99, smooth=5)
    t_scores = det.score(series, smooth=5)
    z_scores = moving_zscore(series, window=48)
    zs = sorted(z_scores[:900])
    z_thr = zs[int(0.99 * len(zs))]

    t_auc, z_auc = roc_auc(t_scores, labels), roc_auc(z_scores, labels)
    t_pa = point_adjusted_f1(labels, scores_to_labels(t_scores, thr))["f1"]
    z_pa = point_adjusted_f1(labels, scores_to_labels(z_scores, z_thr))["f1"]

    plt.rcParams.update({"font.size": 10, "axes.spines.top": False,
                         "axes.spines.right": False})
    fig, ax = plt.subplots(3, 1, figsize=(10, 7.2), sharex=True,
                           gridspec_kw={"height_ratios": [1.2, 1, 1]})
    x = range(len(series))
    panels = [
        (series, "Synthetic series (first 720 points are clean training data)",
         None, None, GREY),
        (t_scores, f"Transformer autoencoder score  |  AUC {t_auc:.2f}, "
                   f"point-adjusted F1 {t_pa:.2f}", thr, "threshold", BLUE),
        (z_scores, f"Moving z-score baseline  |  AUC {z_auc:.2f}, "
                   f"point-adjusted F1 {z_pa:.2f}", z_thr, "threshold", GREEN),
    ]
    for a, (y, title, t, tl, c) in zip(ax, panels):
        for s, e in episodes(labels):
            a.axvspan(s, e, color=RED, alpha=0.15, lw=0)
        a.plot(x, y, color=c, lw=1)
        if t is not None:
            a.axhline(t, color=RED, ls="--", lw=1, label=tl)
            a.legend(loc="upper left", frameon=False)
        a.axvline(720, color="#999999", ls=":", lw=1)
        a.set_title(title, loc="left", fontsize=10)
        a.grid(axis="y", alpha=0.25)
    ax[-1].set_xlabel("timestep")
    fig.text(0.01, 0.005,
             "Red bands: planted anomaly episodes. Synthetic data from "
             "ts_anomaly.TimeSeriesGenerator (seed 7). Reproduce: "
             "python examples/plot_results.py", fontsize=8, color=GREY)
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    out = os.path.join(os.path.dirname(__file__), "..", "docs", "detection.png")
    fig.savefig(out, dpi=150)
    print(f"transformer AUC {t_auc:.3f} PA-F1 {t_pa:.3f} | "
          f"zscore AUC {z_auc:.3f} PA-F1 {z_pa:.3f}\nwrote {out}")


if __name__ == "__main__":
    main()
